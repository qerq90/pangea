package pangea.model.item

import zio.test._

/** «Упырь», порог 10: чужая кровь идёт вампирам в лечение и делится ровно между
  * теми, кто стоит на одной стороне. Правило написано под будущее, где вампиров
  * в бою может быть несколько; сегодня он один — сам герой. */
object GhoulBleedShareSpec extends ZIOSpecDefault {

  private val share = ItemSet.Ghoul.bleedHealShare _

  override def spec = suite("Упырь: делёж чужой крови")(

    test("один вампир забирает всю кровь соперников") {
      assertTrue(share(100L, 1) == 100L) &&
      assertTrue(share(7L, 1) == 7L)
    },

    test("двое делят ровно пополам, трое — на три") {
      assertTrue(share(100L, 2) == 50L) &&
      assertTrue(share(99L, 3) == 33L) &&
      // остаток не раздаётся дважды: сумма долей не больше самой крови
      assertTrue((2 to 5).forall(n => share(100L, n) * n <= 100L))
    },

    test("нет вампиров или нет крови — лечить нечем") {
      assertTrue(share(100L, 0) == 0L) &&
      assertTrue(share(100L, -1) == 0L) &&
      assertTrue(share(0L, 2) == 0L) &&
      assertTrue(share(-5L, 2) == 0L)
    },

    test("считается кровь ЧУЖОЙ стороны и вампиры СВОЕЙ, а не все кровоточащие") {
      // Три вампира у нас, кровь соперников — сто: каждому по тридцать три.
      // Сколько при этом крови течёт у нас самих и сколько вампиров у них, на
      // этот счёт не влияет — такие числа в правило просто не входят.
      assertTrue(share(100L, 3) == 33L) &&
      // та же сторона с одним вампиром получила бы всё
      assertTrue(share(100L, 1) == 100L)
    }
  )
}
