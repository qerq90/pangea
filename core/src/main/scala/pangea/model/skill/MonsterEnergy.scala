package pangea.model.skill

import pangea.model.monster.Rarity

/**
 * Энергия обычных мобов — ресурс, из которого они платят за свои умения. Пришла
 * на смену «шансу каста»: раньше умение выпадало броском кубика и игрок никак не
 * мог на это повлиять, теперь оно копится, его видно на экране боя и его можно
 * сбить проком Молнии.
 *
 * Цена и реген растут по уровню ОДИНАКОВО (+2 за уровень), но у цены больше
 * стартовое смещение: 20 против 15. С уровнем эта фора размывается — отношение
 * (20+2·lvl)/(15+2·lvl) сползает с 1.29 к единице, — поэтому вглубь лабиринта
 * умения идут чуть чаще: обычный моб копит 1.4 раунда на первом уровне и ровно
 * раунд на 150-м. Разница невелика; настоящая ручка частоты — редкость, она
 * множит реген (легендарный успевает применить умение каждый раунд).
 *
 * Минибоссы сюда НЕ входят: у них своя энергия от `BossLvL` и жёсткий круг
 * способностей (см. `MiniBoss`).
 */
object MonsterEnergy {

  /** Цена «обычного» умения на этом уровне — единица измерения для всех прочих. */
  def baseCost(lvl: Long): Long = 20L + 2L * lvl

  /** Сколько энергии моб восстанавливает за раунд: редкие копят заметно быстрее. */
  def regen(lvl: Long, rarity: Rarity): Long =
    ((15L + 2L * lvl) * rarity.factor).toLong.max(1L)

  /** Потолок запаса — три обычных умения. Держит моба от того, чтобы скопить на
   *  залп из нескольких умений подряд, пока его долго не добивают. */
  def maxEnergy(lvl: Long): Long = baseCost(lvl) * 3L

  /** Стартовый запас: `pctRoll`% (5–30) от максимума, умноженные на редкость.
   *  Без стартовой энергии обычные мобы не успевали бы показать ни одного умения
   *  за короткий бой — копить с нуля им попросту некогда. */
  def startEnergy(lvl: Long, rarity: Rarity, pctRoll: Long): Long = {
    val max = maxEnergy(lvl)
    ((max * pctRoll * rarity.factor) / 100.0).toLong.max(0L).min(max)
  }

  /** Границы стартового ролла (в % от максимума, до умножения на редкость). */
  val StartPctMin: Long = 5L
  val StartPctMax: Long = 30L

  /** Множитель цены базовых умений — тех, что есть у всех рас. */
  val BasicCostFactor: Double = 0.8

  /** Множитель цены расовых умений вроде «Порошка!». */
  val RacialCostFactor: Double = 1.5

  /** Цена умения = доля базовой, округление ВВЕРХ: дешевле обычного умения не
   *  бывает, а дробей в энергии мы не держим. */
  def cost(lvl: Long, factor: Double): Long =
    math.ceil(baseCost(lvl) * factor).toLong.max(1L)
}
