package pangea.model.battle

/** Единая схема строя — одна на все бои: и на обычную встречу в лабиринте, и на
  * налёт, и на караван с его башнями.
  *
  * Поле боя — два ряда мест, пронумерованных с единицы. На своей стороне герой и
  * союзники занимают [[HeroPlaces]] мест, на чужой стоят до [[MonsterPlaces]]
  * врагов, и место N одной стороны смотрит на место N другой. Чужих мест
  * больше: за одиннадцатым начинается хвост, куда никому из отряда не дотянуться
  * — там стоят стрелковые башни каравана и оттуда подходят те, кто ждал своей
  * очереди. Кому места не хватило, ждут за строем (`GroupState.queue`) и входят,
  * как только оно освободится.
  *
  * Числа держим здесь, а не по месту: стоит их развести, и схема расходится —
  * так и было, пока у отряда было одиннадцать мест, а у мобов десять, и пока
  * караван ставил башни на места, уже занятые охраной. */
object Formation {

  /** Мест на стороне героя: он сам и до десяти союзников. */
  val HeroPlaces: Int = 11

  /** Мест на стороне врага: столько их может стоять против героя разом. */
  val MonsterPlaces: Int = 15
}
