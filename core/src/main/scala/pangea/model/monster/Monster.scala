    * Берётся ПЕРВОЕ свободное из списка, а не новый бросок: имя каждому уже
    * выпало при генерации, здесь только разводятся совпадения. */
  def distinctNames(monsters: List[Monster]): List[Monster] =
    monsters.foldLeft((List.empty[Monster], Set.empty[String])) { case ((acc, used), m) =>
      m.customName match {
        case Some(n) if !used.contains(n) => (acc :+ m, used + n)
        case Some(n) =>
          legendaryNames.getOrElse(m.race, Nil).find(!used.contains(_)) match {
            case Some(free) => (acc :+ m.copy(customName = Some(free)), used + free)
            case None       => (acc :+ m, used + n)
          }
        case None => (acc :+ m, used)
      }
    } match { case (out, _) => out }
}
